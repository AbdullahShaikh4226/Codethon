"""Restore templates shown in the demo: Terraform for AWS and Azure, a Kubernetes manifest for any platform."""
import re

AZURE_SKU = {"Standard_HDD": "Standard_LRS", "Standard_SSD": "StandardSSD_LRS",
             "Premium_SSD": "Premium_LRS", "Ultra": "UltraSSD_LRS"}
AZURE_LOCATION = {"East US": "eastus", "West Europe": "westeurope", "Southeast Asia": "southeastasia"}
AWS_IOPS_RANGE = {"gp3": (3000, 16000), "io2": (100, 64000)}  # st1 and gp2 take no provisioned IOPS


def _header(p50: float, p90: float) -> str:
    return (f"# Generated by GMCR. Forecast restore time: P50 {p50:.1f} min, P90 {p90:.1f} min.\n"
            "# Review before applying; values in var.* must be supplied.\n")


def terraform(platform: str, w: dict, p50: float, p90: float) -> str | None:
    """Restore the disk from a snapshot with the workload's settings. None for VMware (no template)."""
    size = int(round(w["VM_Size_GB"]))
    if platform == "aws":
        vol, region = w["EBS_Volume_Type"], w["Region"]
        iops = ""
        if vol in AWS_IOPS_RANGE:
            lo, hi = AWS_IOPS_RANGE[vol]
            iops = f"  iops              = {min(max(int(w['Provisioned_IOPS']), lo), hi)}\n"
        return _header(p50, p90) + f'''
provider "aws" {{
  region = "{region}"
}}

variable "snapshot_id" {{
  type = string
}}

variable "availability_zone" {{
  type    = string
  default = "{region}a"
}}

resource "aws_ebs_volume" "gmcr_restore" {{
  availability_zone = var.availability_zone
  snapshot_id       = var.snapshot_id
  size              = {size}
  type              = "{vol}"
{iops}
  tags = {{
    Name               = "gmcr-restore"
    gmcr_forecast_p90m = "{p90:.0f}"
  }}
}}
'''
    if platform == "azure":
        sku = AZURE_SKU[w["Disk_Tier"]]
        zone = '  zone                 = "1" # Ultra disks must be zonal\n' if sku == "UltraSSD_LRS" else ""
        return _header(p50, p90) + f'''
provider "azurerm" {{
  features {{}}
}}

variable "resource_group_name" {{
  type = string
}}

variable "source_snapshot_id" {{
  type = string
}}

resource "azurerm_managed_disk" "gmcr_restore" {{
  name                 = "gmcr-restore-disk"
  location             = "{AZURE_LOCATION.get(w['Region'], 'eastus')}"
  resource_group_name  = var.resource_group_name
  storage_account_type = "{sku}"
  create_option        = "Copy"
  source_resource_id   = var.source_snapshot_id
  disk_size_gb         = {size}
{zone}
  tags = {{
    gmcr_forecast_p90m = "{p90:.0f}"
  }}
}}
'''
    return None


def k8s_name(text: str) -> str:
    """RFC 1123 label: lowercase letters, digits and '-', at most 63 characters."""
    return re.sub(r"[^a-z0-9-]+", "-", text.lower()).strip("-")[:63] or "gmcr"


def kubernetes(platform: str, w: dict, p50: float, p90: float, storage_class: str = "standard") -> str:
    name = k8s_name(f"gmcr-restore-{platform}")
    size = int(round(w["VM_Size_GB"]))
    return _header(p50, p90) + f'''apiVersion: v1
kind: Service
metadata:
  name: {name}
  namespace: dr-clean-room
spec:
  clusterIP: None
  selector:
    app: {name}
  ports:
    - port: 443
---
apiVersion: apps/v1
kind: StatefulSet
metadata:
  name: {name}
  namespace: dr-clean-room
spec:
  serviceName: {name}
  replicas: 1
  selector:
    matchLabels:
      app: {name}
  template:
    metadata:
      labels:
        app: {name}
    spec:
      containers:
        - name: recovery-agent
          image: busybox:1.36
          command: ["sh", "-c", "sleep infinity"]  # replace with your restore agent image
          ports:
            - containerPort: 443
          volumeMounts:
            - name: restore-data
              mountPath: /data
  volumeClaimTemplates:
    - metadata:
        name: restore-data
      spec:
        accessModes: ["ReadWriteOnce"]
        storageClassName: {k8s_name(storage_class)}
        resources:
          requests:
            storage: {size}Gi
'''
